<#
.SYNOPSIS
    Correlates user SIDs between source and destination Windows Servers.

.DESCRIPTION
    Takes the CSV user lists generated by user-extractor.ps1 from both the source
    and destination servers, matches them by Username, and generates a correlation CSV
    containing Username, Source Server SID, and Destination Server SID.

.PARAMETER SourceUserFile
    Path to the source server user list CSV.

.PARAMETER TargetUserFile
    Path to the destination/target server user list CSV.

.PARAMETER OutputFile
    Path to the output correlation CSV file.

.EXAMPLE
    .\match-users-sids.ps1 C:\Migration\source_users.csv C:\Migration\target_users.csv C:\Migration\users_correlation.csv
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to the source server user list CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$SourceUserFile,

    [Parameter(Mandatory = $true, Position = 1, HelpMessage = "Path to the target server user list CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$TargetUserFile,

    [Parameter(Mandatory = $true, Position = 2, HelpMessage = "Path to the output correlation CSV file")]
    [ValidateNotNullOrEmpty()]
    [string]$OutputFile
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -Path $SourceUserFile -PathType Leaf)) {
    Write-Error "Source user file not found: $SourceUserFile"
    exit 1
}

if (-not (Test-Path -Path $TargetUserFile -PathType Leaf)) {
    Write-Error "Target user file not found: $TargetUserFile"
    exit 1
}

Write-Host "Loading source users from: $SourceUserFile" -ForegroundColor Cyan
$sourceUsers = Import-Csv -Path $SourceUserFile

Write-Host "Loading target users from: $TargetUserFile" -ForegroundColor Cyan
$targetUsers = Import-Csv -Path $TargetUserFile

# Build target lookup dictionary by Username (case-insensitive)
$targetLookup = [System.Collections.Generic.Dictionary[string, PSCustomObject]]::new([System.StringComparer]::OrdinalIgnoreCase)

foreach ($tu in $targetUsers) {
    $uname = if ($tu.PSObject.Properties['Username']) {
        $tu.Username
    } elseif ($tu.PSObject.Properties['User Name']) {
        $tu.'User Name'
    } else {
        $tu.Name
    }

    if (-not [string]::IsNullOrWhiteSpace($uname)) {
        if (-not $targetLookup.ContainsKey($uname)) {
            $targetLookup.Add($uname, $tu)
        }
    }
}

$correlationList = [System.Collections.Generic.List[PSCustomObject]]::new()
$unmatchedCount = 0

foreach ($su in $sourceUsers) {
    $sName = if ($su.PSObject.Properties['Username']) {
        $su.Username
    } elseif ($su.PSObject.Properties['User Name']) {
        $su.'User Name'
    } else {
        $su.Name
    }

    if ([string]::IsNullOrWhiteSpace($sName)) {
        continue
    }

    $sourceSid = if ($su.PSObject.Properties['User SID']) {
        $su.'User SID'
    } elseif ($su.PSObject.Properties['SID']) {
        $su.SID
    } else {
        ""
    }

    if ($targetLookup.ContainsKey($sName)) {
        $tu = $targetLookup[$sName]
        $targetSid = if ($tu.PSObject.Properties['User SID']) {
            $tu.'User SID'
        } elseif ($tu.PSObject.Properties['SID']) {
            $tu.SID
        } else {
            ""
        }

        $correlationList.Add([PSCustomObject]@{
            'Username'               = $sName
            'Source Server SID'      = $sourceSid
            'Destination Server SID' = $targetSid
        })
    } else {
        Write-Warning "[UNMATCHED] User '$sName' on source server was not found on target server."
        $unmatchedCount++
    }
}

# Ensure output directory exists
$outputDir = Split-Path -Path $OutputFile -Parent
if ($outputDir -and -not (Test-Path -Path $outputDir)) {
    New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
}

$correlationList | Export-Csv -Path $OutputFile -NoTypeInformation -Encoding UTF8

Write-Host "`nUser Matching Summary:" -ForegroundColor Cyan
Write-Host "  Source users:      $($sourceUsers.Count)"
Write-Host "  Target users:      $($targetUsers.Count)"
Write-Host "  Correlated users:  $($correlationList.Count)" -ForegroundColor Green
if ($unmatchedCount -gt 0) {
    Write-Host "  Unmatched users:   $unmatchedCount" -ForegroundColor Yellow
}
Write-Host "Output written to:   $OutputFile" -ForegroundColor Green
