<#
.SYNOPSIS
    Translates SIDs in an icacls SDDL export file from source server to target server SIDs.

.DESCRIPTION
    Takes the correlated user and group CSV files generated by match-users-sids.ps1
    and match-groups-sids.ps1, as well as an SDDL file exported by icacls /save,
    and replaces all occurrences of source server SIDs with the matching destination server SIDs.
    Preserves UTF-16 LE encoding strictly required by icacls /restore.

.PARAMETER UserCorrelationFile
    Path to the user correlation CSV file generated by match-users-sids.ps1.

.PARAMETER GroupCorrelationFile
    Path to the group correlation CSV file generated by match-groups-sids.ps1.

.PARAMETER InputSddlFile
    Path to the source icacls SDDL export file (e.g., exported via icacls /save).

.PARAMETER OutputSddlFile
    Path for the translated output SDDL file to be used with icacls /restore.

.PARAMETER PathPrefixSearch
    Optional path prefix to search and replace in the SDDL file (useful if drive letters or root paths changed).

.PARAMETER PathPrefixReplace
    Optional path prefix replacement string.

.EXAMPLE
    .\translate-icacls-sids.ps1 C:\Migration\users_corr.csv C:\Migration\groups_corr.csv C:\Migration\acls.sddl C:\Migration\acls_translated.sddl

.EXAMPLE
    .\translate-icacls-sids.ps1 users_corr.csv groups_corr.csv acls.sddl acls_translated.sddl -PathPrefixSearch "D:\Shares" -PathPrefixReplace "E:\Shares"
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to user correlation CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$UserCorrelationFile,

    [Parameter(Mandatory = $true, Position = 1, HelpMessage = "Path to group correlation CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$GroupCorrelationFile,

    [Parameter(Mandatory = $true, Position = 2, HelpMessage = "Path to input icacls SDDL file")]
    [ValidateNotNullOrEmpty()]
    [string]$InputSddlFile,

    [Parameter(Mandatory = $true, Position = 3, HelpMessage = "Path to translated output SDDL file")]
    [ValidateNotNullOrEmpty()]
    [string]$OutputSddlFile,

    [Parameter(Mandatory = $false, HelpMessage = "Optional path prefix to find in SDDL file")]
    [string]$PathPrefixSearch,

    [Parameter(Mandatory = $false, HelpMessage = "Optional replacement path prefix in SDDL file")]
    [string]$PathPrefixReplace
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Validate input files
if (-not (Test-Path -Path $UserCorrelationFile -PathType Leaf)) {
    Write-Error "User correlation file not found: $UserCorrelationFile"
    exit 1
}

if (-not (Test-Path -Path $GroupCorrelationFile -PathType Leaf)) {
    Write-Error "Group correlation file not found: $GroupCorrelationFile"
    exit 1
}

if (-not (Test-Path -Path $InputSddlFile -PathType Leaf)) {
    Write-Error "Input SDDL file not found: $InputSddlFile"
    exit 1
}

Write-Host "Loading correlation mappings..." -ForegroundColor Cyan

$userCorrs = Import-Csv -Path $UserCorrelationFile
$groupCorrs = Import-Csv -Path $GroupCorrelationFile

# Mapping dictionary: SourceSID -> DestinationSID
$sidMap = [System.Collections.Generic.Dictionary[string, string]]::new([System.StringComparer]::OrdinalIgnoreCase)
$sidEntityName = [System.Collections.Generic.Dictionary[string, string]]::new([System.StringComparer]::OrdinalIgnoreCase)

function Add-SidMapping {
    param (
        [string]$Name,
        [string]$SourceSid,
        [string]$DestSid,
        [string]$Type
    )
    if ([string]::IsNullOrWhiteSpace($SourceSid) -or [string]::IsNullOrWhiteSpace($DestSid)) {
        return
    }

    $cleanSrc = $SourceSid.Trim()
    $cleanDst = $DestSid.Trim()

    if ($cleanSrc -eq $cleanDst) {
        # Universal SID (e.g. S-1-5-32-544); translation is a no-op
        return
    }

    if (-not $sidMap.ContainsKey($cleanSrc)) {
        $sidMap.Add($cleanSrc, $cleanDst)
        $sidEntityName.Add($cleanSrc, "[$Type] $Name")
    }
}

foreach ($u in $userCorrs) {
    $uname = if ($u.PSObject.Properties['Username']) { $u.Username } else { $u.Name }
    $srcSid = if ($u.PSObject.Properties['Source Server SID']) { $u.'Source Server SID' } else { $u.SourceSid }
    $dstSid = if ($u.PSObject.Properties['Destination Server SID']) { $u.'Destination Server SID' } else { $u.DestinationSid }
    Add-SidMapping -Name $uname -SourceSid $srcSid -DestSid $dstSid -Type 'User'
}

foreach ($g in $groupCorrs) {
    $gname = if ($g.PSObject.Properties['Group']) { $g.Group } elseif ($g.PSObject.Properties['Group Name']) { $g.'Group Name' } else { $g.Name }
    $srcSid = if ($g.PSObject.Properties['Source server SID']) { $g.'Source server SID' } elseif ($g.PSObject.Properties['Source Server SID']) { $g.'Source Server SID' } else { $g.SourceSid }
    $dstSid = if ($g.PSObject.Properties['Destination Server SID']) { $g.'Destination Server SID' } else { $g.DestinationSid }
    Add-SidMapping -Name $gname -SourceSid $srcSid -DestSid $dstSid -Type 'Group'
}

Write-Host "Total distinct SIDs to translate: $($sidMap.Count)" -ForegroundColor Cyan

# Sort Source SIDs by length descending to prevent shorter SIDs from corrupting longer SIDs
$sortedSourceSids = $sidMap.Keys | Sort-Object -Property Length -Descending

# Read SDDL content using UTF-16 LE (Unicode), standard for icacls /save
Write-Host "Reading SDDL content from: $InputSddlFile" -ForegroundColor Cyan
$rawBytes = [System.IO.File]::ReadAllBytes($InputSddlFile)

# Detect encoding: icacls /save uses UTF-16 LE (BOM: FF FE)
$encoding = [System.Text.Encoding]::Unicode
if ($rawBytes.Length -ge 3 -and $rawBytes[0] -eq 0xEF -and $rawBytes[1] -eq 0xBB -and $rawBytes[2] -eq 0xBF) {
    Write-Host "Detected UTF-8 BOM encoding on input file." -ForegroundColor Yellow
    $encoding = [System.Text.Encoding]::UTF8
} elseif ($rawBytes.Length -ge 2 -and $rawBytes[0] -eq 0xFF -and $rawBytes[1] -eq 0xFE) {
    Write-Host "Detected standard icacls UTF-16 LE (Unicode) encoding." -ForegroundColor Green
    $encoding = [System.Text.Encoding]::Unicode
} else {
    # Check for null bytes alternating, typical for UTF-16 LE without BOM
    $nullByteCount = 0
    $sampleLen = [Math]::Min($rawBytes.Length, 100)
    for ($i = 1; $i -lt $sampleLen; $i += 2) {
        if ($rawBytes[$i] -eq 0) { $nullByteCount++ }
    }
    if ($nullByteCount -gt 20) {
        $encoding = [System.Text.Encoding]::Unicode
    } else {
        $encoding = [System.Text.Encoding]::UTF8
    }
}

$sddlContent = $encoding.GetString($rawBytes)

# Optional Path Prefix Translation
if (-not [string]::IsNullOrWhiteSpace($PathPrefixSearch)) {
    $replaceWith = if ($PathPrefixReplace) { $PathPrefixReplace } else { "" }
    Write-Host "Replacing path prefix '$PathPrefixSearch' with '$replaceWith'..." -ForegroundColor Cyan
    $sddlContent = $sddlContent.Replace($PathPrefixSearch, $replaceWith)
}

# Translate SIDs
$totalReplacements = 0
$replacementSummary = [System.Collections.Generic.List[PSCustomObject]]::new()

foreach ($srcSid in $sortedSourceSids) {
    $dstSid = $sidMap[$srcSid]
    $entity = $sidEntityName[$srcSid]

    # Pattern matches SID bounded by non-alphanumeric/hyphen before, and non-digit/hyphen after (allowing delimiters like ;, ), G:, D:, S:)
    $regexPattern = "(?<![A-Za-z0-9\-])" + [System.Text.RegularExpressions.Regex]::Escape($srcSid) + "(?![\d\-])"

    $matches = [System.Text.RegularExpressions.Regex]::Matches($sddlContent, $regexPattern)
    $matchCount = $matches.Count

    if ($matchCount -gt 0) {
        $sddlContent = [System.Text.RegularExpressions.Regex]::Replace($sddlContent, $regexPattern, $dstSid)
        $totalReplacements += $matchCount
        $replacementSummary.Add([PSCustomObject]@{
            'Entity'       = $entity
            'Source SID'   = $srcSid
            'Target SID'   = $dstSid
            'Replacements' = $matchCount
        })
    }
}

# Check for any remaining untranslated S-1-5-21 SIDs in the content
$remainingSids = [System.Text.RegularExpressions.Regex]::Matches($sddlContent, 'S-1-5-21-(?:\d+-){3}\d+') |
    ForEach-Object { $_.Value } |
    Select-Object -Unique

$untranslatedWarnings = 0
foreach ($remSid in $remainingSids) {
    # Check if this SID was in any target SIDs
    $isTargetSid = $sidMap.Values -contains $remSid
    if (-not $isTargetSid) {
        Write-Warning "[NOTICE] Untranslated local SID '$remSid' detected in SDDL. Verify if this principal was on the source server."
        $untranslatedWarnings++
    }
}

# Ensure output directory exists
$outputDir = Split-Path -Path $OutputSddlFile -Parent
if ($outputDir -and -not (Test-Path -Path $outputDir)) {
    New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
}

# Write output strictly using UTF-16 LE with BOM (Unicode), required by icacls /restore
[System.IO.File]::WriteAllText($OutputSddlFile, $sddlContent, [System.Text.Encoding]::Unicode)

Write-Host "`nTranslation Summary:" -ForegroundColor Cyan
Write-Host "  Total distinct SIDs mapped:    $($sidMap.Count)"
Write-Host "  Total replacements performed:  $totalReplacements" -ForegroundColor Green
if ($untranslatedWarnings -gt 0) {
    Write-Host "  Untranslated SIDs found:       $untranslatedWarnings" -ForegroundColor Yellow
}
Write-Host "  Translated SDDL saved to:      $OutputSddlFile (UTF-16 LE)" -ForegroundColor Green

if ($replacementSummary.Count -gt 0) {
    Write-Host "`nReplacements Breakdown:" -ForegroundColor Cyan
    $replacementSummary | Format-Table -AutoSize
} else {
    Write-Warning "No occurrences of source SIDs were found in the input SDDL file."
}
