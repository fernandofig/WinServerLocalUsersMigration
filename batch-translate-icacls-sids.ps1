<#
.SYNOPSIS
    Batch translates SIDs in multiple icacls SDDL files matching a wildcard pattern.

.DESCRIPTION
    Helper script for translate-icacls-sids.ps1. Takes the user and group correlation CSV files
    and a wildcard pattern matching SDDL files (e.g. *.sddl). Iterates over each matched file,
    runs translate-icacls-sids.ps1 on it, and saves the translated file into a "translated"
    subdirectory relative to the original SDDL file.

.PARAMETER UserCorrelationFile
    Path to the user correlation CSV file generated by match-users-sids.ps1.

.PARAMETER GroupCorrelationFile
    Path to the group correlation CSV file generated by match-groups-sids.ps1.

.PARAMETER Pattern
    Wildcard pattern matching SDDL files to process (e.g. *.sddl or C:\Migration\*.sddl).

.PARAMETER OutputSubdirectory
    Name of the subdirectory where translated files will be placed. Defaults to 'translated'.

.PARAMETER PathPrefixSearch
    Optional path prefix to search and replace in the SDDL files.

.PARAMETER PathPrefixReplace
    Optional replacement path prefix in the SDDL files.

.EXAMPLE
    .\batch-translate-icacls-sids.ps1 users_corr.csv groups_corr.csv "*.sddl"

.EXAMPLE
    .\batch-translate-icacls-sids.ps1 C:\Migration\users_corr.csv C:\Migration\groups_corr.csv "C:\Data\*.sddl" -PathPrefixSearch "D:\Data" -PathPrefixReplace "E:\Data"
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to user correlation CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$UserCorrelationFile,

    [Parameter(Mandatory = $true, Position = 1, HelpMessage = "Path to group correlation CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$GroupCorrelationFile,

    [Parameter(Mandatory = $true, Position = 2, HelpMessage = "Wildcard pattern of SDDL files (e.g. *.sddl)")]
    [ValidateNotNullOrEmpty()]
    [string]$Pattern,

    [Parameter(Mandatory = $false, HelpMessage = "Subdirectory name for translated files (default: 'translated')")]
    [string]$OutputSubdirectory = 'translated',

    [Parameter(Mandatory = $false, HelpMessage = "Optional path prefix to find in SDDL files")]
    [string]$PathPrefixSearch,

    [Parameter(Mandatory = $false, HelpMessage = "Optional replacement path prefix in SDDL files")]
    [string]$PathPrefixReplace
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Locate translate-icacls-sids.ps1 in the same directory as this script
$scriptDir = Split-Path -Path $MyInvocation.MyCommand.Path -Parent
$translateScript = Join-Path -Path $scriptDir -ChildPath "translate-icacls-sids.ps1"

if (-not (Test-Path -Path $translateScript -PathType Leaf)) {
    Write-Error "Could not find translate-icacls-sids.ps1 at expected path: $translateScript"
    exit 1
}

# Validate correlation files
if (-not (Test-Path -Path $UserCorrelationFile -PathType Leaf)) {
    Write-Error "User correlation file not found: $UserCorrelationFile"
    exit 1
}

if (-not (Test-Path -Path $GroupCorrelationFile -PathType Leaf)) {
    Write-Error "Group correlation file not found: $GroupCorrelationFile"
    exit 1
}

Write-Host "================================================================================" -ForegroundColor Cyan
Write-Host "Batch SDDL Translation Started" -ForegroundColor Cyan
Write-Host "User Correlation:  $UserCorrelationFile" -ForegroundColor Cyan
Write-Host "Group Correlation: $GroupCorrelationFile" -ForegroundColor Cyan
Write-Host "Pattern:           $Pattern" -ForegroundColor Cyan
Write-Host "Output Subfolder:  $OutputSubdirectory" -ForegroundColor Cyan
Write-Host "================================================================================" -ForegroundColor Cyan

# Find matching files
try {
    $files = @(Get-ChildItem -Path $Pattern -File -ErrorAction Stop)
} catch {
    Write-Error "Error searching for pattern '$Pattern': $($_.Exception.Message)"
    exit 1
}

if ($files.Count -eq 0) {
    Write-Warning "No files found matching pattern: $Pattern"
    exit 0
}

Write-Host "Found $($files.Count) SDDL file(s) matching pattern." -ForegroundColor Green

$totalFiles = $files.Count
$successCount = 0
$failCount = 0
$currentIndex = 0

foreach ($file in $files) {
    $currentIndex++
    Write-Host "`n--------------------------------------------------------------------------------" -ForegroundColor Cyan
    Write-Host "[$currentIndex/$totalFiles] Processing file: $($file.FullName)" -ForegroundColor Cyan
    Write-Host "--------------------------------------------------------------------------------" -ForegroundColor Cyan

    $parentDir = $file.DirectoryName
    $targetDir = Join-Path -Path $parentDir -ChildPath $OutputSubdirectory

    if (-not (Test-Path -Path $targetDir -PathType Container)) {
        Write-Host "Creating output directory: $targetDir" -ForegroundColor DarkGray
        New-Item -ItemType Directory -Path $targetDir -Force | Out-Null
    }

    $outputFile = Join-Path -Path $targetDir -ChildPath $file.Name

    $params = @{
        UserCorrelationFile  = $UserCorrelationFile
        GroupCorrelationFile = $GroupCorrelationFile
        InputSddlFile        = $file.FullName
        OutputSddlFile       = $outputFile
    }

    if (-not [string]::IsNullOrWhiteSpace($PathPrefixSearch)) {
        $params['PathPrefixSearch'] = $PathPrefixSearch
    }
    if (-not [string]::IsNullOrWhiteSpace($PathPrefixReplace)) {
        $params['PathPrefixReplace'] = $PathPrefixReplace
    }

    try {
        & $translateScript @params
        $successCount++
        Write-Host "[SUCCESS] Translated file saved to: $outputFile" -ForegroundColor Green
    } catch {
        Write-Error "Failed to translate file '$($file.FullName)': $($_.Exception.Message)"
        $failCount++
    }
}

Write-Host "`n================================================================================" -ForegroundColor Cyan
Write-Host "Batch Translation Summary:" -ForegroundColor Cyan
Write-Host "  Total files matched:   $totalFiles"
Write-Host "  Successfully processed: $successCount" -ForegroundColor Green
if ($failCount -gt 0) {
    Write-Host "  Failed files:           $failCount" -ForegroundColor Red
}
Write-Host "================================================================================" -ForegroundColor Cyan
