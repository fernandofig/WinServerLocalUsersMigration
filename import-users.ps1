<#
.SYNOPSIS
    Imports local users from a CSV file generated by user-extractor.ps1.

.DESCRIPTION
    Creates missing local users on the destination Windows Server with a temporary password
    and flags them so the user must change their password at next logon.
    Existing users are skipped.

.PARAMETER InputFile
    Path to the input CSV file containing users to import.

.PARAMETER ExportCredentialsFile
    Optional path to export a CSV containing newly created usernames and their temporary passwords.

.PARAMETER DefaultPassword
    Optional plain text or SecureString password to use for all newly created accounts.
    If not specified, a strong cryptographically random 16-character password is generated for each account.

.EXAMPLE
    .\import-users.ps1 C:\Migration\source_users.csv

.EXAMPLE
    .\import-users.ps1 C:\Migration\source_users.csv -ExportCredentialsFile C:\Migration\temp_passwords.csv
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to the input CSV file")]
    [ValidateNotNullOrEmpty()]
    [string]$InputFile,

    [Parameter(Mandatory = $false, HelpMessage = "Optional CSV file to save temporary credentials for new users")]
    [string]$ExportCredentialsFile,

    [Parameter(Mandatory = $false, HelpMessage = "Optional default password for all newly created accounts")]
    [string]$DefaultPassword
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function New-TemporaryPassword {
    [CmdletBinding()]
    param (
        [int]$Length = 16
    )
    $upperChars = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    $lowerChars = "abcdefghijkmnopqrstuvwxyz"
    $digitChars = "23456789"
    $specialChars = "!@#$%^&*()-_=+"
    $allChars = $upperChars + $lowerChars + $digitChars + $specialChars

    $bytes = [byte[]]::new($Length)
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)

    $chars = [char[]]::new($Length)
    # Ensure at least one character from each set
    $chars[0] = $upperChars[$bytes[0] % $upperChars.Length]
    $chars[1] = $lowerChars[$bytes[1] % $lowerChars.Length]
    $chars[2] = $digitChars[$bytes[2] % $digitChars.Length]
    $chars[3] = $specialChars[$bytes[3] % $specialChars.Length]

    for ($i = 4; $i -lt $Length; $i++) {
        $chars[$i] = $allChars[$bytes[$i] % $allChars.Length]
    }

    # Shuffle characters
    $rnd = [System.Random]::new()
    $shuffled = $chars | Sort-Object { $rnd.Next() }
    return -join $shuffled
}

if (-not (Test-Path -Path $InputFile -PathType Leaf)) {
    Write-Error "Input file not found: $InputFile"
    exit 1
}

Write-Host "Reading user list from: $InputFile" -ForegroundColor Cyan
$users = Import-Csv -Path $InputFile

if (-not $users -or $users.Count -eq 0) {
    Write-Warning "The input CSV file is empty. No users to import."
    exit 0
}

$hasLocalUserCmdlets = [bool](Get-Command -Name Get-LocalUser -ErrorAction SilentlyContinue)
$createdCredentials = [System.Collections.Generic.List[PSCustomObject]]::new()

$totalProcessed = 0
$totalCreated = 0
$totalSkipped = 0

foreach ($row in $users) {
    $totalProcessed++

    # Extract fields supporting alternative header naming
    $username = if ($row.PSObject.Properties['Username']) {
        $row.Username
    } elseif ($row.PSObject.Properties['User Name']) {
        $row.'User Name'
    } else {
        $row.Name
    }

    if ([string]::IsNullOrWhiteSpace($username)) {
        Write-Warning "Row $totalProcessed has an empty username. Skipping."
        continue
    }

    $fullName = if ($row.PSObject.Properties['Full name']) {
        $row.'Full name'
    } elseif ($row.PSObject.Properties['FullName']) {
        $row.FullName
    } else {
        ""
    }

    $description = if ($row.PSObject.Properties['Description']) {
        $row.Description
    } else {
        ""
    }

    # Check if user already exists
    $userExists = $false
    if ($hasLocalUserCmdlets) {
        $existing = Get-LocalUser -Name $username -ErrorAction SilentlyContinue
        if ($existing) { $userExists = $true }
    } else {
        try {
            $adsiCheck = [ADSI]"WinNT://$env:COMPUTERNAME/$username,user"
            if ($adsiCheck.Name) { $userExists = $true }
        } catch { }
    }

    if ($userExists) {
        Write-Host "[SKIP] User '$username' already exists on target server." -ForegroundColor Yellow
        $totalSkipped++
        continue
    }

    # Determine password
    $tempPassword = if (-not [string]::IsNullOrWhiteSpace($DefaultPassword)) {
        $DefaultPassword
    } else {
        New-TemporaryPassword
    }

    $securePwd = ConvertTo-SecureString $tempPassword -AsPlainText -Force

    try {
        if ($hasLocalUserCmdlets) {
            $userParams = @{
                Name                 = $username
                Password             = $securePwd
                PasswordNeverExpires = $false
            }
            if (-not [string]::IsNullOrWhiteSpace($fullName)) { $userParams['FullName'] = $fullName }
            if (-not [string]::IsNullOrWhiteSpace($description)) { $userParams['Description'] = $description }

            New-LocalUser @userParams | Out-Null
        } else {
            # ADSI fallback
            $adsiComputer = [ADSI]"WinNT://$env:COMPUTERNAME"
            $newUser = $adsiComputer.Create('User', $username)
            if (-not [string]::IsNullOrWhiteSpace($fullName)) { $newUser.FullName = $fullName }
            if (-not [string]::IsNullOrWhiteSpace($description)) { $newUser.Description = $description }
            $newUser.SetPassword($tempPassword)
            $newUser.SetInfo()
        }

        # Set "User must change password at next logon"
        $changePasswordSet = $false
        try {
            $adsiUser = [ADSI]"WinNT://$env:COMPUTERNAME/$username,user"
            $adsiUser.PasswordExpired = 1
            $adsiUser.SetInfo()
            $changePasswordSet = $true
        } catch {
            try {
                & net.exe user $username /logonpasswordchg:yes | Out-Null
                $changePasswordSet = $true
            } catch {
                Write-Warning "Could not flag 'User must change password at next logon' for user '$username': $($_.Exception.Message)"
            }
        }

        Write-Host "[CREATED] User '$username' created successfully." -ForegroundColor Green
        $totalCreated++

        $createdCredentials.Add([PSCustomObject]@{
            'Username'                  = $username
            'TemporaryPassword'         = $tempPassword
            'MustChangePasswordAtLogon' = $changePasswordSet
        })
    } catch {
        Write-Error "Failed to create user '$username': $($_.Exception.Message)"
    }
}

Write-Host "`nImport Summary:" -ForegroundColor Cyan
Write-Host "  Total users processed: $totalProcessed"
Write-Host "  Created:               $totalCreated" -ForegroundColor Green
Write-Host "  Skipped (existing):    $totalSkipped" -ForegroundColor Yellow

if (-not [string]::IsNullOrWhiteSpace($ExportCredentialsFile) -and $createdCredentials.Count -gt 0) {
    $exportDir = Split-Path -Path $ExportCredentialsFile -Parent
    if ($exportDir -and -not (Test-Path -Path $exportDir)) {
        New-Item -ItemType Directory -Path $exportDir -Force | Out-Null
    }
    $createdCredentials | Export-Csv -Path $ExportCredentialsFile -NoTypeInformation -Encoding UTF8
    Write-Host "`nTemporary passwords exported to: $ExportCredentialsFile" -ForegroundColor Cyan
} elseif ($createdCredentials.Count -gt 0 -and [string]::IsNullOrWhiteSpace($DefaultPassword)) {
    Write-Host "`n[NOTE] You did not specify -ExportCredentialsFile. Here are the generated temporary passwords:" -ForegroundColor Yellow
    $createdCredentials | Format-Table -AutoSize
}
