<#
.SYNOPSIS
    Imports local groups and their members from a CSV file generated by group-extractor.ps1.

.DESCRIPTION
    Creates missing local groups on the destination Windows Server and assigns users to their
    respective groups based on the pipe-separated members list.
    Existing groups are skipped from creation, but their member lists are still processed.
    If a user member does not exist on the target server, a warning is logged and the script continues.

.PARAMETER InputFile
    Path to the input CSV file containing groups to import.

.EXAMPLE
    .\import-groups.ps1 C:\Migration\source_groups.csv
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to the input CSV file")]
    [ValidateNotNullOrEmpty()]
    [string]$InputFile
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -Path $InputFile -PathType Leaf)) {
    Write-Error "Input file not found: $InputFile"
    exit 1
}

Write-Host "Reading group list from: $InputFile" -ForegroundColor Cyan
$groups = Import-Csv -Path $InputFile

if (-not $groups -or $groups.Count -eq 0) {
    Write-Warning "The input CSV file is empty. No groups to import."
    exit 0
}

$hasLocalCmdlets = [bool](Get-Command -Name Get-LocalGroup -ErrorAction SilentlyContinue)

$totalProcessed = 0
$totalCreated = 0
$totalSkipped = 0
$totalMembersAdded = 0
$totalWarnings = 0

foreach ($row in $groups) {
    $totalProcessed++

    # Extract group name
    $groupName = if ($row.PSObject.Properties['Group Name']) {
        $row.'Group Name'
    } elseif ($row.PSObject.Properties['GroupName']) {
        $row.GroupName
    } elseif ($row.PSObject.Properties['Group']) {
        $row.Group
    } else {
        $row.Name
    }

    if ([string]::IsNullOrWhiteSpace($groupName)) {
        Write-Warning "Row $totalProcessed has an empty group name. Skipping."
        continue
    }

    $description = if ($row.PSObject.Properties['Description']) {
        $row.Description
    } else {
        ""
    }

    # Extract member list string
    $membersRaw = if ($row.PSObject.Properties['Members user list'] -and -not [string]::IsNullOrWhiteSpace($row.'Members user list')) {
        $row.'Members user list'
    } elseif ($row.PSObject.Properties['Members'] -and -not [string]::IsNullOrWhiteSpace($row.Members)) {
        $row.Members
    } else {
        ""
    }

    # Check if group already exists
    $groupExists = $false
    if ($hasLocalCmdlets) {
        $existingGroup = Get-LocalGroup -Name $groupName -ErrorAction SilentlyContinue
        if ($existingGroup) { $groupExists = $true }
    } else {
        try {
            $adsiCheck = [ADSI]"WinNT://$env:COMPUTERNAME/$groupName,group"
            if ($adsiCheck.Name) { $groupExists = $true }
        } catch { }
    }

    if ($groupExists) {
        Write-Host "[EXISTS] Group '$groupName' already exists. Skipping group creation." -ForegroundColor Yellow
        $totalSkipped++
    } else {
        try {
            if ($hasLocalCmdlets) {
                $grpParams = @{ Name = $groupName }
                if (-not [string]::IsNullOrWhiteSpace($description)) { $grpParams['Description'] = $description }
                New-LocalGroup @grpParams | Out-Null
            } else {
                $adsiComputer = [ADSI]"WinNT://$env:COMPUTERNAME"
                $newGrp = $adsiComputer.Create('Group', $groupName)
                if (-not [string]::IsNullOrWhiteSpace($description)) { $newGrp.Description = $description }
                $newGrp.SetInfo()
            }
            Write-Host "[CREATED] Group '$groupName' created successfully." -ForegroundColor Green
            $totalCreated++
        } catch {
            Write-Error "Failed to create group '$groupName': $($_.Exception.Message)"
            continue
        }
    }

    # Process membership allocation
    if (-not [string]::IsNullOrWhiteSpace($membersRaw)) {
        $memberList = $membersRaw -split '\|' | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' }

        # Query existing members in target group to prevent duplicates
        $currentMemberNames = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
        if ($hasLocalCmdlets) {
            try {
                $existingMembers = Get-LocalGroupMember -Group $groupName -ErrorAction SilentlyContinue
                foreach ($em in $existingMembers) {
                    $mName = [string]$em.Name
                    $mClean = if ($mName -match '\\([^\\]+)$') { $Matches[1] } else { $mName }
                    $currentMemberNames.Add($mClean) | Out-Null
                }
            } catch { }
        }

        foreach ($member in $memberList) {
            if ($currentMemberNames.Contains($member)) {
                Write-Host "  -> Member '$member' is already in group '$groupName'." -ForegroundColor DarkGray
                continue
            }

            # Check if user exists on target server
            $userFound = $false
            if ($hasLocalCmdlets) {
                $targetUser = Get-LocalUser -Name $member -ErrorAction SilentlyContinue
                if ($targetUser) { $userFound = $true }
            } else {
                try {
                    $uCheck = [ADSI]"WinNT://$env:COMPUTERNAME/$member,user"
                    if ($uCheck.Name) { $userFound = $true }
                } catch { }
            }

            if (-not $userFound) {
                Write-Warning "[WARNING] Member '$member' could not be added to group '$groupName' because user does not exist on this server."
                $totalWarnings++
                continue
            }

            try {
                if ($hasLocalCmdlets) {
                    Add-LocalGroupMember -Group $groupName -Member $member -ErrorAction Stop
                } else {
                    $adsiGrp = [ADSI]"WinNT://$env:COMPUTERNAME/$groupName,group"
                    $adsiGrp.Add("WinNT://$env:COMPUTERNAME/$member")
                }
                Write-Host "  -> Added member '$member' to group '$groupName'." -ForegroundColor Cyan
                $totalMembersAdded++
                $currentMemberNames.Add($member) | Out-Null
            } catch {
                Write-Warning "Could not add member '$member' to group '$groupName': $($_.Exception.Message)"
                $totalWarnings++
            }
        }
    }
}

Write-Host "`nImport Summary:" -ForegroundColor Cyan
Write-Host "  Total groups processed: $totalProcessed"
Write-Host "  Created:                $totalCreated" -ForegroundColor Green
Write-Host "  Skipped (existing):     $totalSkipped" -ForegroundColor Yellow
Write-Host "  Memberships added:      $totalMembersAdded" -ForegroundColor Cyan
if ($totalWarnings -gt 0) {
    Write-Host "  Warnings (missing users): $totalWarnings" -ForegroundColor Red
}
