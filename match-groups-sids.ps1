<#
.SYNOPSIS
    Correlates group SIDs between source and destination Windows Servers.

.DESCRIPTION
    Takes the CSV group lists generated by group-extractor.ps1 from both the source
    and destination servers, matches them by Group Name, and generates a correlation CSV
    containing Group, Source server SID, and Destination Server SID.

.PARAMETER SourceGroupFile
    Path to the source server group list CSV.

.PARAMETER TargetGroupFile
    Path to the destination/target server group list CSV.

.PARAMETER OutputFile
    Path to the output correlation CSV file.

.EXAMPLE
    .\match-groups-sids.ps1 C:\Migration\source_groups.csv C:\Migration\target_groups.csv C:\Migration\groups_correlation.csv
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0, HelpMessage = "Path to the source server group list CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$SourceGroupFile,

    [Parameter(Mandatory = $true, Position = 1, HelpMessage = "Path to the target server group list CSV")]
    [ValidateNotNullOrEmpty()]
    [string]$TargetGroupFile,

    [Parameter(Mandatory = $true, Position = 2, HelpMessage = "Path to the output correlation CSV file")]
    [ValidateNotNullOrEmpty()]
    [string]$OutputFile
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -Path $SourceGroupFile -PathType Leaf)) {
    Write-Error "Source group file not found: $SourceGroupFile"
    exit 1
}

if (-not (Test-Path -Path $TargetGroupFile -PathType Leaf)) {
    Write-Error "Target group file not found: $TargetGroupFile"
    exit 1
}

Write-Host "Loading source groups from: $SourceGroupFile" -ForegroundColor Cyan
$sourceGroups = Import-Csv -Path $SourceGroupFile

Write-Host "Loading target groups from: $TargetGroupFile" -ForegroundColor Cyan
$targetGroups = Import-Csv -Path $TargetGroupFile

# Build target lookup dictionary by Group Name (case-insensitive)
$targetLookup = [System.Collections.Generic.Dictionary[string, PSCustomObject]]::new([System.StringComparer]::OrdinalIgnoreCase)

foreach ($tg in $targetGroups) {
    $gname = if ($tg.PSObject.Properties['Group Name']) {
        $tg.'Group Name'
    } elseif ($tg.PSObject.Properties['GroupName']) {
        $tg.GroupName
    } elseif ($tg.PSObject.Properties['Group']) {
        $tg.Group
    } else {
        $tg.Name
    }

    if (-not [string]::IsNullOrWhiteSpace($gname)) {
        if (-not $targetLookup.ContainsKey($gname)) {
            $targetLookup.Add($gname, $tg)
        }
    }
}

$correlationList = [System.Collections.Generic.List[PSCustomObject]]::new()
$unmatchedCount = 0

foreach ($sg in $sourceGroups) {
    $sName = if ($sg.PSObject.Properties['Group Name']) {
        $sg.'Group Name'
    } elseif ($sg.PSObject.Properties['GroupName']) {
        $sg.GroupName
    } elseif ($sg.PSObject.Properties['Group']) {
        $sg.Group
    } else {
        $sg.Name
    }

    if ([string]::IsNullOrWhiteSpace($sName)) {
        continue
    }

    $sourceSid = if ($sg.PSObject.Properties['Group SID']) {
        $sg.'Group SID'
    } elseif ($sg.PSObject.Properties['SID']) {
        $sg.SID
    } else {
        ""
    }

    if ($targetLookup.ContainsKey($sName)) {
        $tg = $targetLookup[$sName]
        $targetSid = if ($tg.PSObject.Properties['Group SID']) {
            $tg.'Group SID'
        } elseif ($tg.PSObject.Properties['SID']) {
            $tg.SID
        } else {
            ""
        }

        $correlationList.Add([PSCustomObject]@{
            'Group'                  = $sName
            'Source server SID'      = $sourceSid
            'Destination Server SID' = $targetSid
        })
    } else {
        Write-Warning "[UNMATCHED] Group '$sName' on source server was not found on target server."
        $unmatchedCount++
    }
}

# Ensure output directory exists
$outputDir = Split-Path -Path $OutputFile -Parent
if ($outputDir -and -not (Test-Path -Path $outputDir)) {
    New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
}

$correlationList | Export-Csv -Path $OutputFile -NoTypeInformation -Encoding UTF8

Write-Host "`nGroup Matching Summary:" -ForegroundColor Cyan
Write-Host "  Source groups:      $($sourceGroups.Count)"
Write-Host "  Target groups:      $($targetGroups.Count)"
Write-Host "  Correlated groups:  $($correlationList.Count)" -ForegroundColor Green
if ($unmatchedCount -gt 0) {
    Write-Host "  Unmatched groups:   $unmatchedCount" -ForegroundColor Yellow
}
Write-Host "Output written to:    $OutputFile" -ForegroundColor Green
